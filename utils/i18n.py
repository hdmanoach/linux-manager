from flask import session

LANGS = ("fr", "en")
DEFAULT_LANG = "fr"


def get_lang():
    """Langue courante (session, 'fr' par défaut)."""
    lang = session.get("lang", DEFAULT_LANG)
    return lang if lang in LANGS else DEFAULT_LANG


def t(key):
    """Traduit une clé. Repli : français, puis la clé elle-même."""
    try:
        lang = get_lang()
    except RuntimeError:
        lang = DEFAULT_LANG
    return TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS["fr"].get(key, key)


